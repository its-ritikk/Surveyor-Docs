const flatten = (items) => {
  const res = [];
  for (const item of items) {
    if (item.to && !item.to.includes("#")) {
      res.push({ label: item.label, to: item.to });
    }
    if (item.children) {
      res.push(...flatten(item.children));
    }
  }
  return res;
};

export const flatNav = nav.flatMap((g) => flatten(g.items));
